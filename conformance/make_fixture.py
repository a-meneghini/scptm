"""
Generate the shared metric/stats fixture both packages must reproduce.

Run from the repository root:

    python conformance/make_fixture.py

The output (``metrics_fixture.json``) is checked in, so the two test suites
verify against a frozen artefact instead of against each other's live code —
which is the only way to catch a silent divergence in a deliberately duplicated
implementation.
"""
import json
from pathlib import Path

import numpy as np
from scipy import sparse


def build():
    rng = np.random.default_rng(20240501)
    pools = [
        "rocket orbit launch satellite mission".split(),
        "hockey puck goal playoff team".split(),
        "faith prayer church god belief".split(),
        "graphics image file format pixel".split(),
    ]
    docs = [[str(rng.choice(pool)) for _ in range(12)] for _ in range(24) for pool in pools]
    vocab = sorted({w for d in docs for w in d})
    index = {w: i for i, w in enumerate(vocab)}
    rows, cols = [], []
    for r, doc in enumerate(docs):
        for w in doc:
            rows.append(r)
            cols.append(index[w])
    bow = sparse.csr_matrix(
        (np.ones(len(rows)), (rows, cols)), shape=(len(docs), len(vocab))
    )
    bow.sum_duplicates()
    topics = [vocab[0:5], vocab[5:10], vocab[10:15], vocab[0:3] + vocab[15:17]]
    return docs, vocab, bow, topics


def main():
    docs, vocab, bow, topics = build()

    # the metrics module is imported from the *bow* package here; both must agree
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scptm-bow"))
    import scptm_bow.metrics as M
    import scptm_bow.stats as S

    metrics = {
        "c_v": M.c_v_coherence(topics, tokenized=docs, window=5),
        "npmi": M.npmi_coherence(topics, bow, vocab),
        "diversity": M.topic_diversity(topics),
        "redundancy": M.redundancy(topics),
    }

    a = [0.351, 0.362, 0.349, 0.371, 0.355, 0.360]
    b = [0.301, 0.315, 0.298, 0.322, 0.309, 0.311]
    stats = {
        "cliffs_delta": S.cliffs_delta(a, b),
        "cohens_dz": S.cohens_dz(a, b),
        "paired_ci_estimate": S.paired_bootstrap_ci(a, b, n_resamples=4000, seed=3).estimate,
        "paired_ci_low": S.paired_bootstrap_ci(a, b, n_resamples=4000, seed=3).low,
        "paired_ci_high": S.paired_bootstrap_ci(a, b, n_resamples=4000, seed=3).high,
        "wilcoxon_p": S.wilcoxon_paired(a, b).p_value,
        "holm": list(S.holm([0.01, 0.04, 0.03]).round(10)),
    }

    payload = {
        "_note": "generated by conformance/make_fixture.py — do not edit by hand",
        "tokens": docs,
        "vocab": vocab,
        "bow_shape": list(bow.shape),
        "bow_nnz": [[int(r), int(c), float(v)] for r, c, v in zip(*sparse.find(bow))],
        "topics": topics,
        "metrics": metrics,
        "stats": {
            "a": a, "b": b,
            **{k: (float(v) if not isinstance(v, list) else v) for k, v in stats.items()},
        },
    }
    out = Path(__file__).resolve().parent / "metrics_fixture.json"
    out.write_text(json.dumps(payload, indent=2, ensure_ascii=False))
    print(f"scritto {out} ({out.stat().st_size} byte)")
    for k, v in metrics.items():
        print(f"  {k:<12} {v:.10f}")


if __name__ == "__main__":
    main()
